"""The migrations must build exactly the schema the models declare.

Without this, Alembic is worse than `create_all`: the application would run
migrations at start-up while the tests build their schema from the models, and
the two could drift apart silently for a whole sprint. These tests fail the
moment someone changes a model without generating a revision.
"""
import sqlalchemy as sa

from app.db.base import Base
from app.db.migrations import alembic_config


def _upgrade_to_head(db_path):
    """Run every migration against an empty SQLite file and inspect the result."""
    from alembic import command

    url = f"sqlite:///{db_path}"
    cfg = alembic_config()
    cfg.set_main_option("sqlalchemy.url", url)
    command.upgrade(cfg, "head")
    return sa.create_engine(url)


def test_migrations_create_every_model_table(tmp_path):
    engine = _upgrade_to_head(tmp_path / "migrated.db")
    migrated = set(sa.inspect(engine).get_table_names()) - {"alembic_version"}
    declared = set(Base.metadata.tables)

    assert migrated == declared, (
        f"only in migrations: {sorted(migrated - declared)}; "
        f"only in models: {sorted(declared - migrated)}"
    )


def test_migrated_columns_match_the_models(tmp_path):
    engine = _upgrade_to_head(tmp_path / "migrated.db")
    inspector = sa.inspect(engine)

    mismatches = []
    for name, table in Base.metadata.tables.items():
        migrated_cols = {c["name"] for c in inspector.get_columns(name)}
        declared_cols = set(table.columns.keys())
        if migrated_cols != declared_cols:
            mismatches.append(
                f"{name}: only in migration {sorted(migrated_cols - declared_cols)}, "
                f"only in model {sorted(declared_cols - migrated_cols)}"
            )

    assert not mismatches, "; ".join(mismatches)


def test_head_has_no_pending_model_changes(tmp_path):
    """An un-generated model change is a drift bug; `alembic check` catches it."""
    from alembic import command
    from alembic.util.exc import AutogenerateDiffsDetected

    cfg = alembic_config()
    cfg.set_main_option("sqlalchemy.url", f"sqlite:///{tmp_path / 'check.db'}")
    command.upgrade(cfg, "head")

    try:
        command.check(cfg)
    except AutogenerateDiffsDetected as exc:  # pragma: no cover - only on drift
        raise AssertionError(
            f"models and migrations have drifted apart: {exc}. "
            "Run: python -m alembic revision --autogenerate -m '<change>'"
        ) from exc


def test_adopts_a_database_that_has_tables_but_no_revision(tmp_path, monkeypatch):
    """A create_all-era or half-migrated database must be stamped, not re-created.

    Regression: the first version of this guard only checked whether the
    alembic_version *table* existed. A migration run that dies part-way leaves
    that table created but empty, so the check waved it through to an upgrade
    that then failed on the first CREATE TABLE -- and the application could not
    start at all until the file was deleted by hand.
    """
    import sqlalchemy as sa

    from app.db import migrations as mig

    db = tmp_path / "legacy.db"
    engine = sa.create_engine(f"sqlite:///{db}")

    # A database as create_all would leave it: every table, no revision stamped.
    Base.metadata.create_all(engine)
    with engine.begin() as conn:
        conn.execute(sa.text("CREATE TABLE alembic_version (version_num VARCHAR(32) NOT NULL)"))

    monkeypatch.setattr(mig, "engine", engine)
    original = mig.alembic_config

    def config_pointed_at_the_temp_db():
        cfg = original()
        cfg.set_main_option("sqlalchemy.url", f"sqlite:///{db}")
        return cfg

    monkeypatch.setattr(mig, "alembic_config", config_pointed_at_the_temp_db)

    mig.run_migrations()  # must not raise

    assert mig.current_revision() is not None, "database was left without a revision"
